"""Utilidades compartidas de Data Pump (respaldos y recuperación)."""
import os
import re
import shutil
import subprocess
import tempfile
import threading
from datetime import datetime

import config
from db import get_connection, query_dicts

DIR_NAME = "BACKUP_DIR"
IDENT = re.compile(r"^[A-Za-z][A-Za-z0-9_$#]{0,29}$")

_DDL_HISTORIAL = """
CREATE TABLE system.bkp_historial (
    id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operacion VARCHAR2(10),
    tipo      VARCHAR2(10),
    objetos   VARCHAR2(1000),
    archivo   VARCHAR2(260),
    logfile   VARCHAR2(260),
    estado    VARCHAR2(20),
    inicio    DATE,
    fin       DATE,
    tamano_mb NUMBER,
    mensaje   VARCHAR2(2000)
)"""


def ensure_historial():
    with get_connection() as conn:
        with conn.cursor() as cur:
            cur.execute("SELECT COUNT(*) FROM dba_tables WHERE owner='SYSTEM' "
                        "AND table_name='BKP_HISTORIAL'")
            if cur.fetchone()[0] == 0:
                cur.execute(_DDL_HISTORIAL)


def ident(valor, campo):
    if not IDENT.match(valor or ""):
        raise ValueError(f"{campo} inválido: use letras, números o _ (máx. 30).")
    return valor.upper()


def dir_path(nombre=DIR_NAME):
    r = query_dicts("SELECT directory_path FROM dba_directories WHERE directory_name=:d",
                    {"d": nombre})
    return r[0]["DIRECTORY_PATH"] if r else None


def default_path():
    """Ruta por defecto: la de DATA_PUMP_DIR, que el servicio Oracle puede escribir."""
    return dir_path("DATA_PUMP_DIR")


def set_directory(ruta):
    ruta = (ruta or "").strip().rstrip("\\/")
    if not ruta or "'" in ruta or '"' in ruta:
        raise ValueError("Ruta inválida.")
    os.makedirs(ruta, exist_ok=True)
    with get_connection() as conn:
        with conn.cursor() as cur:
            cur.execute(f"CREATE OR REPLACE DIRECTORY {DIR_NAME} AS '{ruta}'")


def tool(nombre):
    exe = shutil.which(nombre)
    if not exe:
        home = os.getenv("ORACLE_HOME")
        if home and os.path.exists(os.path.join(home, "bin", nombre + ".exe")):
            exe = os.path.join(home, "bin", nombre + ".exe")
    if not exe:
        raise RuntimeError(f"No se encontró {nombre}.exe: agregue ORACLE_HOME\\bin al PATH.")
    return exe


def _userid():
    cred = f"{config.DB_USER}/{config.DB_PASSWORD}@{config.DB_HOST}:{config.DB_PORT}/{config.DB_SERVICE}"
    if config.DB_SYSDBA:
        cred += " as sysdba"
    return f'"{cred}"'


def nuevo_registro(operacion, tipo, objetos, archivo, logfile):
    with get_connection() as conn:
        with conn.cursor() as cur:
            idv = cur.var(int)
            cur.execute(
                "INSERT INTO system.bkp_historial (operacion,tipo,objetos,archivo,logfile,"
                "estado,inicio) VALUES (:o,:t,:ob,:a,:l,'EN CURSO',SYSDATE) "
                "RETURNING id INTO :id",
                dict(o=operacion, t=tipo, ob=objetos[:1000], a=archivo, l=logfile, id=idv))
            conn.commit()
            return idv.getvalue()[0]


def _leer_log(path):
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            return f.read()
    except OSError:
        return ""


def _worker(registro, exe, params, directorio, archivo, logfile, es_export):
    fd, parfile = tempfile.mkstemp(suffix=".par", prefix="dp_")
    estado, mensaje = "ERROR", ""
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(f"userid={_userid()}\n")
            f.write(f"directory={DIR_NAME}\n")
            for linea in params:
                f.write(linea + "\n")
        proc = subprocess.run([exe, f"parfile={parfile}"], capture_output=True, text=True,
                              errors="replace", creationflags=0x08000000)
        salida = proc.stdout + proc.stderr
        log = _leer_log(os.path.join(directorio, logfile)) or salida
        if "successfully completed" in log and proc.returncode == 0:
            estado = "OK"
        elif "completed with" in log:
            estado = "ADVERTENCIA"
        errores = re.findall(r"^(?:ORA|UDE|LRM)-\d+.*$", log + "\n" + salida, re.M)
        mensaje = "\n".join(errores[:8])[:2000]
        if estado == "ERROR" and not mensaje:
            mensaje = salida[-1500:]
    except Exception as e:  # noqa: BLE001
        mensaje = str(e)[:2000]
    finally:
        try:
            os.remove(parfile)
        except OSError:
            pass
        tam = None
        if es_export:
            ruta = os.path.join(directorio, archivo)
            if os.path.exists(ruta):
                tam = round(os.path.getsize(ruta) / 1048576, 2)
        with get_connection() as conn:
            with conn.cursor() as cur:
                cur.execute("UPDATE system.bkp_historial SET estado=:e, fin=SYSDATE, "
                            "tamano_mb=:t, mensaje=:m WHERE id=:i",
                            dict(e=estado, t=tam, m=mensaje, i=registro))
            conn.commit()


def lanzar(operacion, tipo, objetos, archivo, logfile, params, es_export):
    """Registra la operación y ejecuta expdp/impdp en un hilo de fondo."""
    ensure_historial()
    directorio = dir_path()
    if not directorio:
        raise ValueError("Primero configure el directorio de respaldos.")
    exe = tool("expdp" if es_export else "impdp")
    reg = nuevo_registro(operacion, tipo, objetos, archivo, logfile)
    threading.Thread(target=_worker, daemon=True,
                     args=(reg, exe, params, directorio, archivo, logfile, es_export)).start()
    return reg


def marca():
    return datetime.now().strftime("%Y%m%d_%H%M%S")
